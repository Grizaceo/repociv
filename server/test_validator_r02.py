def test_must_pass_failure_remains_fail(monkeypatch: pytest.MonkeyPatch) -> None:
    _scaffold("R02-9")
    _wi.write_validation_contract(
        REPO, "R02-9",
        {"goal": "Ship the widget", "deliverables": ["widget.ts"],
         "mustPassChecks": ["tests-pass"], "behaviourChecks": ["renders"],
         "evidenceRequired": ["screenshot"], "doneDefinition": "done",
         "autoGenerated": False},
    )
    monkeypatch.setattr(
        _validator, "_check_must_pass_checks",
        lambda repo, issue_id: [{
            "id": "tests-pass", "label": "Tests pass",
            "passed": False, "detail": "1 failed",
        }],
    )

    result = _validator.validate_issue(REPO, "R02-9")

    assert result["verdict"] == "fail"
    assert "Must-pass checks failed" in result["summary"]


def test_critical_failure_remains_fail() -> None:
    """Missing spec is critical: verdict is fail regardless of contract quality."""
    _wi.init_issue_workspace(REPO, "R02-10")
    _wi.write_plan(REPO, "R02-10", "Step 1: implement\nStep 2: verify\n")
    _wi.add_artifact(REPO, "R02-10", "result.txt", content="artifact\n")
    # spec.md absent.

    result = _validator.validate_issue(REPO, "R02-10")

    assert result["verdict"] == "fail"
    assert "Critical checks failed" in result["summary"]
