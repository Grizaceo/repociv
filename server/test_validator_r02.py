"""R02 regression tests: validation verdict semantics.

Guards the roadmap R02 acceptance criteria (docs/audits/p1-r02-evidence.md):

1. An auto-generated contract with an empty goal and a failing non-critical
   check never produces validated success ("pass").
2. Missing objective, missing behavioural evidence, or missing artifacts
   cannot silently upgrade a task to verified success.
3. Existing valid documented contracts retain their documented pass/fail
   behavior.

Every test is inert: no models, no live agents, no subprocess execution.
`_check_must_pass_checks` is stubbed so no pytest/ruff/build command runs.
"""
from __future__ import annotations

import tempfile
from pathlib import Path

import pytest

import server.validator as _validator
import server.workspace_issue as _wi
import server.locks as _locks

REPO = "r02-fixture-repo"


@pytest.fixture(autouse=True)
def _isolated_workspace(monkeypatch: pytest.MonkeyPatch) -> None:
    """Fresh in-memory workspace store + stubbed must-pass runner."""
    _wi._reset()
    _locks._reset()
    tmp = tempfile.mkdtemp(prefix="repociv-r02-")
    _wi.init(Path(tmp))

    # Never execute a real tool during these tests.
    monkeypatch.setattr(
        _validator, "_check_must_pass_checks", lambda repo, issue_id: []
    )
    yield
    _wi._reset()
    _locks._reset()


def _scaffold(issue_id: str, *, spec: str = "Goal\n- do the thing thoroughly\n", plan: str = "Step 1: implement\nStep 2: verify\n", artifacts: tuple[str, ...] = ("result.txt",)) -> None:
    _wi.init_issue_workspace(REPO, issue_id)
    _wi.write_spec(REPO, issue_id, spec)
    _wi.write_plan(REPO, issue_id, plan)
    for name in artifacts:
        _wi.add_artifact(REPO, issue_id, name, content=f"artifact {name}\n")


def _fail_plan_check(monkeypatch: pytest.MonkeyPatch) -> None:
    """Make the plan-present check fail (non-critical, not must-pass)."""
    monkeypatch.setattr(
        _validator, "_check_plan_present",
        lambda repo, issue_id: {
            "id": "plan-present",
            "label": "Plan is present and non-trivial",
            "passed": False,
            "detail": "plan.md is missing or too short (< 20 chars)",
        },
    )


# ── 1. R02 primary regression ───────────────────────────────────────────────

def test_auto_generated_contract_with_failing_check_is_never_a_pass(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Auto-gen contract, empty goal, one failing non-critical check → no pass."""
    _scaffold("R02-1", plan="too short", artifacts=())
    _wi.write_validation_contract(
        REPO, "R02-1",
        {"goal": "", "deliverables": [], "mustPassChecks": [],
         "behaviourChecks": [], "evidenceRequired": [], "doneDefinition": "",
         "autoGenerated": True},
    )
    _fail_plan_check(monkeypatch)

    result = _validator.validate_issue(REPO, "R02-1")

    assert result["verdict"] != "pass"
    assert result["verdict"] == "needs-human-review"
    assert "auto-generated contract with an empty goal" in result["summary"]
    assert result["limitations"]


def test_auto_generated_minimal_contract_all_checks_pass_is_not_a_pass() -> None:
    """Even with every structural check green, an empty auto-gen contract is not success."""
    _scaffold("R02-2")
    _wi.write_validation_contract(
        REPO, "R02-2",
        {"goal": "", "deliverables": [], "mustPassChecks": [],
         "behaviourChecks": [], "evidenceRequired": [], "doneDefinition": "",
         "autoGenerated": True},
    )

    result = _validator.validate_issue(REPO, "R02-2")

    assert result["verdict"] == "needs-human-review"
    assert result["verdict"] != "pass"
    assert any("auto-generated contract" in lim for lim in result["limitations"])


# ── 2. Missing evidence cannot upgrade to verified success ──────────────────

def test_empty_goal_contract_is_needs_human_review() -> None:
    _scaffold("R02-3")
    _wi.write_validation_contract(
        REPO, "R02-3",
        {"goal": "   ", "deliverables": ["a file"],
         "mustPassChecks": [], "behaviourChecks": [], "evidenceRequired": [],
         "doneDefinition": "done", "autoGenerated": False},
    )

    result = _validator.validate_issue(REPO, "R02-3")

    assert result["verdict"] == "needs-human-review"
    assert "contract goal is empty" in result["summary"]


def test_documented_contract_without_behavioural_evidence_is_not_a_pass() -> None:
    _scaffold("R02-4")
    _wi.write_validation_contract(
        REPO, "R02-4",
        {"goal": "Ship the widget", "deliverables": ["widget.ts"],
         "mustPassChecks": [], "behaviourChecks": [], "evidenceRequired": [],
         "doneDefinition": "widget exists and renders", "autoGenerated": False},
    )

    result = _validator.validate_issue(REPO, "R02-4")

    assert result["verdict"] == "needs-human-review"
    assert "no behavioural evidence" in result["summary"]


def test_missing_artifacts_never_upgrades_to_success() -> None:
    """A documented contract with no artifacts produced must not be a green pass."""
    _scaffold("R02-5", artifacts=())
    _wi.write_validation_contract(
        REPO, "R02-5",
        {"goal": "Ship the widget", "deliverables": ["widget.ts"],
         "mustPassChecks": [], "behaviourChecks": ["renders"],
         "evidenceRequired": ["screenshot"], "doneDefinition": "done",
         "autoGenerated": False},
    )

    result = _validator.validate_issue(REPO, "R02-5")

    assert result["verdict"] == "needs-human-review"
    assert any(not c["passed"] and c["id"] == "artifacts-exist"
               for c in result["technical_checks"])


def test_no_contract_at_all_is_a_fail_not_a_pass() -> None:
    """Missing contract is a critical failure: verdict stays fail, never pass."""
    _scaffold("R02-6")
    # No contract written for R02-6.
    result = _validator.validate_issue(REPO, "R02-6")

    assert result["verdict"] == "fail"
    assert any(not c["passed"] and c["id"] == "contract-exists"
               for c in result["technical_checks"])


