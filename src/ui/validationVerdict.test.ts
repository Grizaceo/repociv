// ─── Unit tests for the validation verdict UI module ─────────────────────────
// Tests cover formatting and rendering of validation results in the task panel.
import { describe, it, expect } from 'vitest';
import { formatValidationResult, renderValidationResult } from './validationVerdict.ts';

describe('validationVerdict', () => {
  it('formats a "pass" verdict correctly', () => {
    const result = {
      verdict: 'pass' as const,
      summary: 'All validation checks passed',
      technical_checks: [
        {
          id: 'contract-exists',
          label: 'Contract exists',
          passed: true,
          detail: 'Contract v1.0 present (autoGenerated=false)',
        },
        {
          id: 'spec-present',
          label: 'Spec is present',
          passed: true,
          detail: 'spec.md: 123 chars',
        },
      ],
      behaviour_checks: [],
      evidence: [
        '[PASS] Contract exists: Contract v1.0 present (autoGenerated=false)',
        '[PASS] Spec is present: spec.md: 123 chars',
      ],
      followups: [],
    };

    const formatted = formatValidationResult(result);

    expect(formatted.verdict).toBe('pass');
    expect(formatted.verdict_label).toBe('✓ Validated');
    expect(formatted.html).toContain('background:');
    expect(formatted.html).toContain('✓ Validated');
    expect(formatted.html).toContain('All validation checks passed');
  });

  it('formats a "fail" verdict correctly', () => {
    const result = {
      verdict: 'fail' as const,
      summary: 'Critical checks failed: Spec is present and non-trivial',
      technical_checks: [
        { id: 'contract-exists', label: 'Contract exists', passed: true, detail: '' },
        {
          id: 'spec-present',
          label: 'Spec is present',
          passed: false,
          detail: 'spec.md is missing or too short (< 20 chars)',
        },
      ],
      behaviour_checks: [],
      evidence: [],
      followups: ['Fix critical issues and re-run validation'],
      limitations: [],
    };

    const formatted = formatValidationResult(result);

    expect(formatted.verdict).toBe('fail');
    expect(formatted.verdict_label).toBe('✗ Validation Failed');
    expect(formatted.html).toContain('✗ Validation Failed');
    expect(formatted.html).toContain('Critical checks failed');
  });

  it('formats a "needs-human-review" verdict with limitations', () => {
    const result = {
      verdict: 'needs-human-review' as const,
      summary:
        'Contract is insufficient for a verified pass: auto-generated contract with an empty goal',
      technical_checks: [
        { id: 'contract-exists', label: 'Contract exists', passed: true, detail: '' },
        {
          id: 'contract-goal',
          label: 'Contract has a goal',
          passed: false,
          detail: 'Contract goal is empty',
        },
      ],
      behaviour_checks: [],
      evidence: [],
      followups: [
        'Define the contract goal, deliverables, and done definition, then re-run validation',
      ],
      limitations: [
        'auto-generated contract with an empty goal',
        'failed non-critical checks: Contract has a goal',
      ],
    };

    const formatted = formatValidationResult(result);

    expect(formatted.verdict).toBe('needs-human-review');
    expect(formatted.verdict_label).toBe('⚠️ Needs Human Review');
    expect(formatted.html).toContain('⚠️ Needs Human Review');
    expect(formatted.html).toContain('auto-generated contract');
    expect(formatted.limitations_html).toContain('Why Not Verified Success?');
  });

  it('includes missing behavioural evidence in limitations', () => {
    const result = {
      verdict: 'needs-human-review' as const,
      summary: 'All checks passed, but the contract declares no behavioural evidence',
      technical_checks: [
        { id: 'contract-exists', label: 'Contract exists', passed: true, detail: '' },
        { id: 'spec-present', label: 'Spec is present', passed: true, detail: '' },
      ],
      behaviour_checks: [],
      evidence: [],
      followups: [
        'Add behavioural evidence requirements to the contract, or have a human accept the result',
      ],
      limitations: [
        'contract declares no behaviourChecks or evidenceRequired; behaviour_checks were not evaluated',
      ],
    };

    const formatted = formatValidationResult(result);

    expect(formatted.limitations_html).toContain('behaviour_checks were not evaluated');
  });

  it('renders validation result into an element', () => {
    const container = { innerHTML: '' } as unknown as HTMLElement;
    const result = {
      verdict: 'pass' as const,
      summary: 'Test pass',
      technical_checks: [],
      behaviour_checks: [],
      evidence: [],
      followups: [],
    };

    renderValidationResult(container, result);

    expect(container.innerHTML).toContain('Test pass');
    expect(container.innerHTML).toContain('✓ Validated');
  });
});
